_TOKEN = re.compile(r"[a-z0-9+#.]+")


def tokenize_skill(name: str) -> set[str]:
    return set(_TOKEN.findall(name.lower()))


def canonical_topic(name: str) -> str | None:
    """Map a free-text skill name to a built-in topic, or None."""
    lowered = name.strip().lower()
    for topic in TOPICS:
        if lowered == topic.lower():
            return topic
    tokens = tokenize_skill(name)
    for topic, spec in TOPICS.items():
        if tokens & spec["aliases"]:
            return topic
    return None


def available_topics() -> list[str]:
    return list(TOPICS)


def build_skill_questions(topic: str, n: int = 5) -> list[dict]:
    """Return n shuffled MCQs: [{prompt, options, correct}] (correct = index into options)."""
    bank: list[Q] = TOPICS[topic]["questions"]
    picked = random.sample(bank, k=min(n, len(bank)))
    out = []
    for q in picked:
        options = [q.correct, q.w1, q.w2, q.w3]
        random.shuffle(options)
        out.append({"prompt": q.prompt, "options": options, "correct": options.index(q.correct)})
    return out
